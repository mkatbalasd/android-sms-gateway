package me.capcom.smsgateway.modules.webhooks

import me.capcom.smsgateway.modules.account.FakeKeyValueStorage
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertThrows
import org.junit.Test

internal class WebhooksSettingsSigningKeyTest {

    @Test
    fun theKeyFromTheServerReplacesTheAutoGeneratedOne() {
        val settings = WebhooksSettings(FakeKeyValueStorage())
        val generated = settings.signingKey

        settings.setSigningKey("KEYKEYKEYKEYKEYKEYKEYKEYKEYKEYKE")

        assertNotEquals(generated, settings.signingKey)
        assertEquals("KEYKEYKEYKEYKEYKEYKEYKEYKEYKEYKE", settings.signingKey)
    }

    @Test
    fun theKeyIsInPlaceBeforeAnyoneReadsTheGeneratedOne() {
        val storage = FakeKeyValueStorage()
        WebhooksSettings(storage).setSigningKey("abc123abc123abc123abc123")

        // A new settings object (the service after a restart) reads the pinned key,
        // it does not generate another one.
        assertEquals("abc123abc123abc123abc123", WebhooksSettings(storage).signingKey)
    }

    @Test
    fun anEmptyKeyIsRefused() {
        val settings = WebhooksSettings(FakeKeyValueStorage())
        assertThrows(IllegalArgumentException::class.java) { settings.setSigningKey("  ") }
    }
}
